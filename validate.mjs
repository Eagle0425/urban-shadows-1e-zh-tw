import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {runInNewContext} from "node:vm";

const get = name => readFileSync(new URL(name, import.meta.url), "utf8");
const sandbox = {window: {}};
runInNewContext(get("content.js"), sandbox);
runInNewContext(get("draft-data.js"), sandbox);
const {chapters, playbooks, terms, guides} = sandbox.window.handbook;
const draft = sandbox.window.localDraft;
const routes = [...chapters, ...playbooks].map(([id]) => id);
assert.equal(new Set(routes).size, routes.length);
assert.equal(chapters.length, 16);
assert.equal(playbooks.length, 16);
assert.equal(playbooks.filter(row => row[4] === "core").length, 10);
assert.equal(playbooks.filter(row => row[4] === "dark").length, 4);
for (const [id, , , , first, last] of chapters) assert(first <= last, id);
for (const id of Object.keys(guides)) assert(routes.includes(id), id);
assert(terms.some(([english, chinese]) => english === "Debt" && chinese === "人情"));
assert.equal(draft.publicEdition, true);
assert.equal(draft.sourceFiles, undefined);
assert.equal(Object.values(draft.chapters).flat().length, 150);
assert.equal(Object.values(draft.chapters).flat().reduce((sum, part) => sum + (part.blocks?.length ?? 0), 0), 6175);
assert.equal(draft.translationProgress.complete, true);
assert.equal(draft.translationProgress.reviewedPdfPages, 445);
assert.equal(draft.pageInventory.filter(page => page.status === "已校對").length, 445);
assert.equal(draft.translationProgress.scopeExceptions.length, 1);
assert.deepEqual(Array.from(draft.translationProgress.scopeExceptions[0].excludedElements), ["店面小招牌文字", "橢圓小招牌文字"]);
const raw = get("draft-data.js");
assert(!raw.includes("file:///"));
assert(!raw.includes("GPT資料庫"));
assert(!get("index.html").includes("basic-moves-zh.pdf"));
for (const asset of get("index.html").matchAll(/(?:src|href)="\.\/([^"]+)"/g)) get(asset[1]);
console.log("Verified public full-text edition: 32 routes, 150 sections, 6175 units, 445 reviewed pages, no local source paths.");
